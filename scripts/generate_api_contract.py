"""Generate reviewable OpenAPI and frontend ports from api_contract.py. No dependencies."""
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from api_contract import OPERATIONS, REQUIREMENTS, SCHEMAS, openapi


def ts(schema):
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "enum" in schema:
        return " | ".join(json.dumps(v) for v in schema["enum"])
    if schema.get("type") == "array":
        return "Array<" + ts(schema["items"]) + ">"
    if schema.get("type") == "object":
        if "properties" not in schema:
            return "Record<string, unknown>"
        return "{ " + "; ".join(json.dumps(k) + ("" if k in schema.get("required", []) else "?") + ": " + ts(v)
                                for k, v in schema["properties"].items()) + " }"
    return {"string": "string", "integer": "number", "boolean": "boolean"}.get(schema.get("type"), "unknown")


def outputs():
    operations = {op["id"]: {k: op[k] for k in ["method", "path", "implemented", "requirement"]} for op in OPERATIONS}
    client = '''/* Generated by scripts/generate_api_contract.py; do not edit. */
'use strict';
const BACKEND_OPERATIONS = ''' + json.dumps(operations, ensure_ascii=False, indent=2) + ''';
class BackNestBackend {
 constructor({token='', baseUrl='', fetchImpl=globalThis.fetch?.bind(globalThis), transport=null}={}) {
  this.token=token; this.baseUrl=baseUrl; this.fetchImpl=fetchImpl; this.transport=transport;
 }
 async invoke(operationId,{path={},query={},body}={}) {
  const operation=BACKEND_OPERATIONS[operationId];
  if(!operation)throw Error('Unknown backend operation: '+operationId);
  if(this.transport)return this.transport(operationId,{path,query,body}); // Qt WebChannel port
  let endpoint=operation.path.replace(/\\{([^}]+)\\}/g,(_,key)=>{
   if(path[key]===undefined)throw Error('Missing path parameter: '+key);
   return encodeURIComponent(String(path[key]));
  });
  const search=new URLSearchParams();
  for(const [key,value] of Object.entries(query))if(value!==undefined)search.set(key,String(value));
  if(search.size)endpoint+='?'+search;
  const response=await this.fetchImpl(this.baseUrl+endpoint,{
   method:operation.method, headers:{'X-BackNest-Token':this.token,...(body===undefined?{}:{'Content-Type':'application/json'})},
   ...(body===undefined?{}:{body:JSON.stringify(body)})
  });
  const result=await response.json();
  if(!response.ok){const error=Error(result.error||'Backend request failed');error.code=result.code||'REQUEST_FAILED';error.status=response.status;error.operationId=operationId;error.capability=result.capability;throw error;}
  return result;
 }
}
globalThis.BackNestBackend=BackNestBackend;
globalThis.BACKEND_OPERATIONS=BACKEND_OPERATIONS;
'''
    declarations = '// Generated. Wire DTOs; credentials/secretRef must never enter persistent UI state.\n'
    declarations += '\n'.join('export type ' + name + ' = ' + ts(schema) + ';' for name, schema in SCHEMAS.items())
    declarations += '\nexport interface BackendOperations {\n'
    for op in OPERATIONS:
        declarations += '  ' + json.dumps(op['id']) + ': { request: ' + (op['request'] or 'undefined') + '; response: ' + op['response'] + ' };\n'
    declarations += '''}
export interface BackendCallOptions { path?: Record<string,string>; query?: Record<string,string|number|boolean>; body?: unknown; }
export interface BackendTransport { (operationId:keyof BackendOperations, args:BackendCallOptions):Promise<unknown>; }
export declare class BackNestBackend {
 constructor(options?:{token?:string; baseUrl?:string; fetchImpl?:typeof fetch; transport?:BackendTransport});
 invoke<K extends keyof BackendOperations>(id:K, options?:BackendCallOptions & {body?:BackendOperations[K]['request']}):Promise<BackendOperations[K]['response']>;
}
export interface WorkspaceRepositoryPort<State=unknown> { load():Promise<State>; save(state:State):Promise<void>; }
'''
    matrix = '# 需求与后端接口覆盖表\n\n由 `api_contract.py` 生成。`reserved` 表示接口预留，不表示算法已实现。\n\n| 要求 | 分值 | 当前状态 | 后端 operationId |\n| --- | --- | --- | --- |\n'
    for requirement in REQUIREMENTS:
        ids = [op['id'] for op in OPERATIONS if op['requirement'] == requirement['id']]
        matrix += '| ' + ' | '.join([requirement['name'], requirement['points'], requirement['status'], ', '.join('`'+i+'`' for i in ids)]) + ' |\n'
    return {
        ROOT / 'api' / 'openapi.json': json.dumps(openapi(), ensure_ascii=False, indent=2) + '\n',
        ROOT / 'api' / 'backend-api.d.ts': declarations,
        ROOT / 'backend-api.js': client,
        ROOT / 'docs' / 'REQUIREMENTS_AUDIT.md': matrix,
    }


if __name__ == '__main__':
    for path, content in outputs().items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding='utf-8')
    print(f'Generated {len(OPERATIONS)} operation contracts across {len(REQUIREMENTS)} requirements.')
